type ControlFlowObserver interface {
	ObserveControlFlow(ControlFlowEvent)
}

func observeControlFlow(observer ControlFlowObserver, event ControlFlowEvent) {
	if observer != nil {
		observer.ObserveControlFlow(event)
	}
}
