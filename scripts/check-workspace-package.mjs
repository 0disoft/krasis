import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { verifyExecutableIcon } from './check-windows-icon.mjs';

const directory=process.argv[2];
assert.ok(directory,'Expected distribution directory');
verifyExecutableIcon(fs.readFileSync(path.join(directory,'krasis.exe')));
const generation = Number(path.basename(directory).match(/^g(\d+)$/u)?.[1]);
assert.ok(Number.isSafeInteger(generation),'Expected generation-scoped distribution');
const expected=['BUILD.json','SHA256SUMS.txt','START-HERE.md','THIRD-PARTY-NOTICES.txt','krasis-agent.exe','krasis-cli.exe','krasis.exe'];
const actual=fs.readdirSync(directory).sort();
const probeNames=['KrasisBrokeredProbe-TESTSIGNED.msix','KrasisBrokeredProbe-TESTCERT.cer'];
const probeCount=probeNames.filter(name=>actual.includes(name)).length;
assert.ok(probeCount===0||probeCount===probeNames.length,'Probe package and certificate must appear together');
if (probeCount===probeNames.length) expected.push(...probeNames);
const uiAccessNames=['KrasisUIAccessProbe-TESTSIGNED.exe','KrasisUIAccessProbe-TESTCERT.cer','TEST-CERT-DETAILS.txt','README.md','install-test.ps1','remove-test.ps1'];
const uiAccessCount=uiAccessNames.filter(name=>actual.includes(name)).length;
assert.ok(uiAccessCount===0||uiAccessCount===uiAccessNames.length,'UIAccess test payload must be complete');
assert.equal(uiAccessCount===uiAccessNames.length,(generation>=91&&generation<=94)||[97,98].includes(generation),'Only the attended g91-g94, g97 and g98 updates carry the UIAccess test payload');
if (uiAccessCount===uiAccessNames.length) expected.push(...uiAccessNames);
assert.deepEqual(actual,expected.sort());
console.log(`UI icon and single-copy ${expected.length}-file update bundle verified.`);
