import { readFileSync, writeFileSync } from 'node:fs';

// One settings catalog feeds the renderer directly and generates Go constants.
// Checking never rewrites source; npm test rejects stale generated constants.
const mode = process.argv[2] ?? '--check';
if (!['--check', '--write'].includes(mode) || process.argv.length > 3) {
  throw new Error('Use --check or --write');
}
const source = new URL('../internal/appsettings/status-contract.json', import.meta.url);
const target = new URL('../internal/appsettings/status_contract.go', import.meta.url);
const contract = JSON.parse(readFileSync(source, 'utf8'));
if (!/^krasis\.app-settings\/v[1-9][0-9]*$/u.test(contract.schema) ||
    !contract.codes || typeof contract.codes !== 'object' || Array.isArray(contract.codes)) {
  throw new Error('Invalid settings contract');
}
const entries = Object.entries(contract.codes);
if (entries.length === 0 || new Set(entries.map(([, value]) => value)).size !== entries.length ||
    entries.some(([name, value]) => !/^[A-Z][A-Za-z0-9]*$/u.test(name) ||
      typeof value !== 'string' || !/^[a-z]+(?:_[a-z]+)*$/u.test(value))) {
  throw new Error('Settings codes require unique named values');
}
const generated = [
  '// Code generated by scripts/generate-app-settings-contract.mjs; DO NOT EDIT.',
  '//go:generate node ../../scripts/generate-app-settings-contract.mjs --write',
  '',
  'package appsettings',
  '',
  `const Schema = ${JSON.stringify(contract.schema)}`,
  '',
  ...entries.map(([name, value]) => `const Status${name} = ${JSON.stringify(value)}`),
  '',
].join('\n');
if (mode === '--write') {
  writeFileSync(target, generated);
} else {
  let current;
  try { current = readFileSync(target, 'utf8').replaceAll('\r\n', '\n'); } catch {}
  if (current !== generated) {
    throw new Error('Settings constants are stale; run node scripts/generate-app-settings-contract.mjs --write');
  }
}
